export const STRINGS = { zh, en };

export function translator(lang) {
  const table = STRINGS[lang] ?? zh;
  return (key, params = {}) =>
    (table[key] ?? zh[key] ?? key).replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ''));
}

/** A person-readable name for a field path such as `$.skin.variants.light.colors.key`. */
export function fieldLabel(lang, path) {
  const t = translator(lang);
  const clean = path.replace(/^\$\.?/, '');
  if (clean === '') return t('f.root');
  const colour = clean.match(/^skin\.variants\.(light|dark)\.colors\.(\w+)$/);
  if (colour) return `${t(`role.${colour[2]}`)}（${t(colour[1])}）`;
  const bare = clean.replace(/^(skin|candidateBar)\./, '');
  const key = `f.${bare}`;
  const label = t(key);
  if (label !== key) return label;
  const top = clean.split('.')[0];
  return t(`f.${top}`);
}

/** `{ message, path }`: short Chinese (or English) text for a FormatError, plus the raw path to show small. */
export function describeError(lang, error) {
  const t = translator(lang);
  const path = error.path ?? '$';
  const field = fieldLabel(lang, path);
  const byReason = {
    color: 'errColor', range: 'errRange', enum: 'errEnum', type: 'errType', id: 'errId', name: 'errName',
    object: 'errObject', background: 'errBackground',
  };
  const message = {
    MALFORMED_JSON: () => t('errMalformed'),
    NOT_AN_OBJECT: () => t('errNotObject'),
    OVERSIZE: () => t('errOversize'),
    UNKNOWN_FIELD: () => t('errUnknown', { field: path.split('.').pop() }),
    UNSUPPORTED_VERSION: () => t('errVersion'),
    INVALID_VALUE: () => t(byReason[error.reason] ?? 'errType', { field }),
    IDENTITY_MISMATCH: () => t('errIdentity'),
    SNAPSHOT_NOT_IMPORTABLE: () => t('errSnapshot'),
    UNRECOGNIZED_DOCUMENT: () => t('errUnrecognized'),
  }[error.code]?.() ?? t('errGeneric');
  return { message, path };
}
